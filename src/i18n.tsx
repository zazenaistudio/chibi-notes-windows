const originalText=new WeakMap<Text,string>();
const originalAttrs=new WeakMap<Element,Map<string,string>>();
const skipSelector='[data-i18n-skip],.note-title,.rich-note-body,.checklist input,.managed-note-title,.notes-mini button b,.notes-mini button small,.title-suggestions button b,.title-suggestions button small,.showcase-note-body,.showcase-note-glass h1,.note-attachments,.group-list h3,.group-list p,.context-menu header b,.move-note-dialog h2,.feature-current-note b';
const attrs=['placeholder','title','data-tooltip','aria-label'];

function skipped(node:Node){const parent=node instanceof Element?node:node.parentElement;return Boolean(parent?.closest(skipSelector));}
function processElement(root:ParentNode,language:AppLanguage){
  const elements=[...(root instanceof Element?[root]:[]),...Array.from(root.querySelectorAll('*'))];
  for(const el of elements){
    if(skipped(el))continue;
    for(const attr of attrs){
      const current=el.getAttribute(attr);if(current===null)continue;
      let map=originalAttrs.get(el);if(!map){map=new Map();originalAttrs.set(el,map);}if(!map.has(attr))map.set(attr,current);
      const original=map.get(attr)!;const translated=translateUi(original,language);if(el.getAttribute(attr)!==translated)el.setAttribute(attr,translated);
    }
    for(const node of Array.from(el.childNodes)){
      if(node.nodeType!==Node.TEXT_NODE||skipped(node))continue;
      const text=node as Text;if(!originalText.has(text))originalText.set(text,text.data);
      const original=originalText.get(text)!;const translated=translateUi(original,language);if(text.data!==translated)text.data=translated;
    }
  }
}

export function I18nRuntime(){
  const language=useAppStore(state=>state.interfaceLanguage);
  useEffect(()=>{
    document.documentElement.lang=language;
    processElement(document.body,language);
    const observer=new MutationObserver(records=>{
      for(const record of records){
        if(record.type==='characterData'&&record.target.parentElement)processElement(record.target.parentElement,language);
        if(record.type==='attributes'&&record.target instanceof Element)processElement(record.target,language);
        for(const node of Array.from(record.addedNodes)){
          if(node instanceof Element)processElement(node,language);
          else if(node.nodeType===Node.TEXT_NODE&&node.parentElement)processElement(node.parentElement,language);
        }
      }
    });
    observer.observe(document.body,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:attrs});
    return()=>observer.disconnect();
  },[language]);
  return null;
}

