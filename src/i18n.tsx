export function translateUi(text:string,language:AppLanguage){
  if(language==='es')return text;
  const trimmed=text.trim();
  const direct=EN[trimmed];
  if(direct)return text.replace(trimmed,direct);
  for(const [regex,replace] of patterns){const match=trimmed.match(regex);if(match)return text.replace(trimmed,replace(match));}
  return text;
}

